import argparse
import os
import sys

from .actions import add_new_client, edit_existing_client, list_clients, remove_client
from .errors import WizardError
from .host import check_root, enable_ip_forwarding, is_root
from .prompts import get_input
from .service import reapply_all_configs, unmanaged_confs
from .store import Session

# Menu actions that change the system and therefore need root.
MUTATING = {'2', '3', '4', '5'}

# State lives next to wizard.py by default, not in whatever directory sudo was started from.
DEFAULT_CONFIG = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "config.json")


def print_startup_warnings(session):
    for problem in session.conflicts():
        print(f"Warning: {problem}", file=sys.stderr)
    known = {c['interface_name'] for c in session.config['clients']}
    for iface in unmanaged_confs(known):
        print(f"Warning: /etc/wireguard/{iface}.conf was generated by this tool but is not in {session.path}; "
              "it will be left alone and its interface name will not be reused.", file=sys.stderr)


def main():
    parser = argparse.ArgumentParser(description="All-in-One WireGuard Configuration Wizard")
    parser.add_argument("-f", "--file", default=DEFAULT_CONFIG,
                        help="Path to the JSON configuration file (default: %(default)s)")
    args = parser.parse_args()

    try:
        with Session(args.file) as session:
            run_menu(session)
    except WizardError as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)


def run_menu(session):
    print("--- WireGuard Multi-Client Wizard ---")

    # Proactively enable IP forwarding if running as root
    if is_root():
        enable_ip_forwarding()
    else:
        print("Warning: not running as root. Add/edit/remove/re-apply will be refused (read-only mode).", file=sys.stderr)
    print_startup_warnings(session)

    while True:
        print("\nMenu:")
        print("1. List existing clients")
        print("2. Add a new client")
        print("3. Edit a client")
        print("4. Remove a client")
        print("5. Re-apply all configurations")
        print("6. Exit")
        try:
            choice = get_input("Choose an option", "1")
        except (KeyboardInterrupt, EOFError):
            print()
            break

        try:
            if choice in MUTATING: check_root()
            if choice == '1': list_clients(session.config)
            elif choice == '2': add_new_client(session)
            elif choice == '3': edit_existing_client(session)
            elif choice == '4': remove_client(session)
            elif choice == '5': reapply_all_configs(session.config)
            elif choice == '6': break
            else: print("Invalid option. Please try again.")
        except WizardError as e:
            print(f"Error: {e}", file=sys.stderr)
        except KeyboardInterrupt:
            print("\nCancelled.")
        except EOFError:
            print()
            break
    print("Run 'sudo wg show' on the server to see live status.")
